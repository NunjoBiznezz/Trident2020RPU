const uint8_t* PeekAnimationBytes(unsigned animationNum, unsigned frameNum) {
   if (animationNum >= NUM_LAMP_ANIMATIONS || frameNum >= LAMP_ANIMATION_STEPS) {
     return nullptr;
   }
   return LampAnimations[animationNum][frameNum];
}

bool FetchAnimationBytes(uint8_t *destinationArray, uint8_t animationNum, uint8_t frameNum) {
  if (destinationArray== nullptr) {
     return false;
  }
  if (animationNum >= NUM_LAMP_ANIMATIONS || frameNum >= LAMP_ANIMATION_STEPS) {
     return false;
  }
  memcpy(destinationArray, LampAnimations[animationNum][frameNum], NUM_LAMP_ANIMATION_BYTES);
  return true;
}
